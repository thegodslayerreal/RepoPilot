def render_dashboard(report: dict[str, Any]) -> str:
    """Render a self-contained dashboard document from an analysis report."""
    payload = json.dumps(report, ensure_ascii=False)
    # Prevent data from terminating the script element or introducing HTML markup.
    payload = (
        payload.replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )

